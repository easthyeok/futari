const fs=require('fs'),vm=require('vm'),assert=require('assert/strict');
const events={},timers=new Map();let id=0,reads=0,removed=0,status,change,notice='';
const window={addEventListener:(k,f)=>events[k]=f,removeEventListener:k=>delete events[k]};
const document={visibilityState:'visible',addEventListener:(k,f)=>events[k]=f,removeEventListener:k=>delete events[k]};
const ctx={window,document,setTimeout:f=>{timers.set(++id,f);return id;},clearTimeout:i=>timers.delete(i)};
vm.runInNewContext(fs.readFileSync(require('path').join(__dirname,'../sync-engine.js'),'utf8'),ctx);
const channel={on(type,filter,cb){change=cb;return this;},subscribe(cb){status=cb;return this;}};
const client={channel:()=>channel,removeChannel:c=>{assert.equal(c,channel);removed++;}};
const tick=()=>{const jobs=[...timers.values()];timers.clear();jobs.forEach(f=>f());};
const stop=window.FutariSync.watch({refresh(){reads++;}},client,'room',v=>notice=v);
for(let i=0;i<100;i++)tick();assert.equal(reads,0,'idle never queries');
status('SUBSCRIBED');events.focus();events.visibilitychange();tick();assert.equal(reads,1,'return and connection events coalesce');
change();tick();assert.equal(reads,2,'remote change queries');
document.visibilityState='hidden';change();events.focus();tick();assert.equal(reads,2,'background does not query');
document.visibilityState='visible';events.visibilitychange();tick();assert.equal(reads,3);
status('CHANNEL_ERROR');assert(notice.includes('실시간 연결이 끊겼어요'));tick();assert.equal(reads,3);
status('SUBSCRIBED');assert.equal(notice,'');tick();assert.equal(reads,4,'reconnect checks missed changes');
events.offline();assert(notice.includes('인터넷'));events.online();tick();assert.equal(reads,5);
change();stop();tick();status('CLOSED');assert.equal(reads,5);assert.equal(removed,1);assert.equal(Object.keys(events).length,0);
console.log('PASS: no idle polling, event coalescing, changes, background/return, disconnect/reconnect and cleanup');
