  function normalize(value){return String(value||'').replace(/\s+/g,'').toLowerCase();}
  function catalog(data){
    var list=MENUS.slice(),known=new Set(list.map(function(x){return normalize(x.name);}));
    (data.foodWishes||[]).forEach(function(item){var name=String(item.name||'').trim();if(name&&!known.has(normalize(name))){known.add(normalize(name));list.push({name:name,description:item.description||item.reason||'둘이 직접 골라 저장한 메뉴예요. 오늘 같이 먹어볼까요?',category:'우리 메뉴'});}});
    return list;
  }
  function foodPool(data,filter){
    filter=filter||{};var query=normalize(filter.query),recent=new Set((data.foodWishes||[]).filter(function(x){return x.done;}).slice().sort(function(a,b){return String(a.eatenAt||'').localeCompare(String(b.eatenAt||''));}).slice(-12).map(function(x){return normalize(x.name);}));
    return catalog(data).filter(function(item){return (!filter.category||filter.category==='전체'||item.category===filter.category)&&(!query||normalize(item.name+' '+item.category+' '+item.description).indexOf(query)>=0)&&(!filter.skipRecent||!recent.has(normalize(item.name)));});
  }
  function shuffle(items,random){
    var list=items.slice();random=random||Math.random;
    for(var i=list.length-1;i>0;i--){var j=Math.floor(random()*(i+1)),temp=list[i];list[i]=list[j];list[j]=temp;}return list;
  }
  // Consume a shuffled deck fully before starting another; never repeat inside a draw.
  function draw(pool,state,count,random){
    var key=JSON.stringify(pool.map(function(x){return x.name;})),byName=new Map(pool.map(function(x){return [x.name,x];}));
    if(state.key!==key){state.key=key;state.remaining=[];state.previous=state.previous||[];}
    var picked=[],limit=Math.min(count||6,pool.length);
    while(picked.length<limit){
      if(!state.remaining.length){
        var next=shuffle(pool.filter(function(x){return !picked.some(function(p){return p.name===x.name;});}),random);
        state.remaining=next.filter(function(x){return state.previous.indexOf(x.name)<0;}).concat(next.filter(function(x){return state.previous.indexOf(x.name)>=0;})).map(function(x){return x.name;});
      }
      var item=byName.get(state.remaining.shift());if(item&&!picked.some(function(x){return x.name===item.name;}))picked.push(item);
    }
    state.previous=picked.map(function(x){return x.name;});return picked;
  }
